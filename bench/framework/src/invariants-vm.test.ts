import { describe, expect, it } from "vitest";
import { checkInvariants, type Snapshot } from "./invariants.js";
import {
  checkNetnsRules,
  parseRule,
  type MicroVmView,
  type VmHostView,
  type VmNetns,
  type VmProcess,
} from "./invariants-vm.js";

/** A namespace's rules as `iptables-save` prints what NetnsPool installs. */
export const GOOD_RULES = `# Generated by iptables-save v1.8.10 (nf_tables)
*nat
:PREROUTING ACCEPT [0:0]
:INPUT ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A PREROUTING -i eth0 -p tcp -m multiport --dports 9000,9223 -j DNAT --to-destination 172.16.0.2
-A PREROUTING -d 172.16.0.1/32 -i tap0 -p tcp -m tcp --dport 3128 -j DNAT --to-destination 172.30.1.1:3128
-A POSTROUTING -o eth0 -j MASQUERADE
-A POSTROUTING -o tap0 -j MASQUERADE
COMMIT
*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
-A INPUT -i lo -j ACCEPT
-A FORWARD -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A FORWARD -d 172.16.0.2/32 -i eth0 -o tap0 -p tcp -m multiport --dports 9000,9223 -m conntrack --ctstate NEW -j ACCEPT
-A FORWARD -s 172.16.0.2/32 -d 172.30.1.1/32 -i tap0 -o eth0 -p tcp -m tcp --dport 3128 -m conntrack --ctstate NEW -j ACCEPT
COMMIT
`;

const VM = "vm-" + "a".repeat(24);
const VM2 = "vm-" + "b".repeat(24);

const nsId = (octet: number) => `net:[40265321${octet - 100}]`;

const proc = (pid: number, over: Partial<VmProcess> = {}): VmProcess => ({
  pid,
  uid: [10002, 10002],
  gid: [10002, 10002],
  capEff: "0000000000000000",
  seccomp: 2,
  noNewPrivs: true,
  cgroup: `/kestrel-vm/${VM}`,
  pidNs: "pid:[4026532001]",
  mntNs: "mnt:[4026532002]",
  netNs: "net:[4026532130]",
  root: { dev: 66306, ino: 1001 },
  ...over,
});

const vm = (id = VM, octet = 130): MicroVmView => ({
  id,
  meta: { node: "a", role: "session", creation: "c1", octet, handlerPid: 501 },
  jail: { root: { dev: 66306, ino: 1001 } },
  vmm: proc(500, { cgroup: `/kestrel-vm/${id}`, netNs: nsId(octet) }),
  handler: proc(501, {
    cgroup: `/kestrel-vm/${id}`,
    seccomp: 0,
    noNewPrivs: false,
    pidNs: null,
    mntNs: null,
    netNs: null,
    root: null,
  }),
  cgroup: {
    cpuMax: "200000 100000",
    memoryMax: String((2048 + 256) * 1024 * 1024),
    swapMax: "0",
    pidsMax: "64",
  },
});

const ns = (octet: number, netNs = nsId(octet)): VmNetns => ({
  name: `kvm-a-${octet}`,
  octet,
  rules: GOOD_RULES,
  ipv6Disabled: true,
  netNs,
});

function host(): VmHostView {
  return {
    node: "a",
    dir: "/data/kestrel-vm",
    cgroupParent: "kestrel-vm",
    bridgeIp: "172.30.1.1",
    egressPort: 3128,
    uid: 10002,
    gid: 10002,
    vcpus: 1,
    memMib: 2048,
    pages: "2M",
    agentNetns: { ready: [131], inUse: [130], making: [] },
    netnsTarget: 8,
    vms: [vm()],
    netns: [ns(130, "net:[4026532130]"), ns(131)],
    veths: [130, 131],
    strayCgroups: [],
    strayJails: [],
    hostPidNs: "pid:[4026531836]",
    hostMntNs: "mnt:[4026531841]",
  };
}

/** A microVM node with one ready session in a VM, and no Docker container at all. */
function good(): Snapshot {
  return {
    docker: [],
    api: [{ id: "ses_1", status: "ready", nodeId: "a", ageSeconds: 5 }],
    agents: [
      {
        node: "a",
        slotsTotal: 4,
        sessions: [
          {
            sessionId: "ses_1",
            state: "ready",
            address: "172.30.1.130",
            containerId: VM,
          },
        ],
        pool: [],
        pendingReports: 0,
        runtime: "microvm",
        creating: [],
        harness: { enabled: true, probePolicies: [], probeVms: [] },
      },
    ],
    egress: [
      {
        node: "a",
        policies: [{ ip: "172.30.1.130", sessionId: "ses_1" }],
        policiesRestored: true,
      },
    ],
    gateways: [{ node: "a", routes: ["ses_1"], attachments: [] }],
    firewall: [{ node: "a", ok: true, problems: [] }],
    failpoints: [],
    failpointsExpected: false,
    harnessExpected: true,
    vms: [host()],
    hugepages: { sizeKb: 2048, total: 7000, free: 6000, reserved: 24 },
  };
}
const rules = (s: Snapshot) => checkInvariants(s).map((v) => v.rule);
const details = (s: Snapshot) => checkInvariants(s).map((v) => v.detail);

describe("namespace rules (G-25)", () => {
  const c = { bridgeIp: "172.30.1.1", egressPort: 3128 };

  it("accepts exactly what NetnsPool installs", () => {
    expect(checkNetnsRules(GOOD_RULES, c)).toEqual([]);
  });

  it("reads a rule by its flags, whatever order iptables prints them in", () => {
    const r = parseRule(
      "-A FORWARD -s 172.16.0.2/32 -d 172.30.1.1/32 -i tap0 -o eth0 -p tcp -m tcp --dport 3128 -j ACCEPT",
    );
    expect(r.chain).toBe("FORWARD");
    expect(r.flags.get("--dport")).toBe("3128");
    expect(r.flags.get("-i")).toBe("tap0");
  });

  it("refuses every way of opening a path", () => {
    const broken: [string, string][] = [
      [
        GOOD_RULES.replace(":FORWARD DROP", ":FORWARD ACCEPT"),
        "FORWARD policy",
      ],
      [GOOD_RULES.replace(":INPUT DROP", ":INPUT ACCEPT"), "INPUT policy"],
      [
        GOOD_RULES.replace(
          "-A INPUT -i lo -j ACCEPT",
          "-A INPUT -i lo -j ACCEPT\n-A INPUT -i tap0 -j ACCEPT",
        ),
        "INPUT accepts",
      ],
      [
        GOOD_RULES.replace("COMMIT\n*filter", "COMMIT\n*filter").replace(
          "-A INPUT -i lo -j ACCEPT",
          "-A INPUT -i lo -j ACCEPT\n-A FORWARD -i tap0 -o eth0 -j ACCEPT",
        ),
        "FORWARD accepts",
      ],
      [
        GOOD_RULES.replace(
          "-d 172.30.1.1/32 -i tap0 -o eth0 -p tcp -m tcp --dport 3128",
          "-d 169.254.169.254/32 -i tap0 -o eth0 -p tcp -m tcp --dport 80",
        ),
        "FORWARD accepts",
      ],
      [
        GOOD_RULES.replace(
          "--dports 9000,9223 -m conntrack",
          "--dports 9000,9222 -m conntrack",
        ),
        "FORWARD accepts",
      ],
      [
        GOOD_RULES.replace(
          "--to-destination 172.30.1.1:3128",
          "--to-destination 169.254.169.254:80",
        ),
        "redirection",
      ],
      [
        GOOD_RULES.replace(
          "-A INPUT -i lo -j ACCEPT",
          "-A INPUT -i lo -j ACCEPT\n-A FORWARD ! -s 10.0.0.0/8 -j ACCEPT",
        ),
        "negated",
      ],
      [
        GOOD_RULES.replace(
          "-A INPUT -i lo -j ACCEPT",
          "-A INPUT -i lo -j ACCEPT\n-A FORWARD -j SOMECHAIN",
        ),
        "unexpected rule",
      ],
      [GOOD_RULES.slice(0, GOOD_RULES.indexOf("*filter")), "no filter table"],
    ];
    for (const [text, why] of broken) {
      const p = checkNetnsRules(text, c);
      expect(p.join("; "), why).toContain(why);
    }
  });
});

describe("the invariant checker on a microVM node (G-25)", () => {
  it("finds nothing wrong with a healthy node", () => {
    expect(checkInvariants(good())).toEqual([]);
  });

  it("finds a VM, or any piece of one, that no agent holds", () => {
    for (const [what, f] of [
      ["a whole VM", (v: MicroVmView) => v],
      [
        "a jail only",
        (v: MicroVmView) => ({
          ...v,
          vmm: null,
          handler: null,
          cgroup: null,
          meta: null,
        }),
      ],
      [
        "a cgroup only",
        (v: MicroVmView) => ({
          ...v,
          vmm: null,
          handler: null,
          jail: null,
          meta: null,
        }),
      ],
      [
        "an agent record only",
        (v: MicroVmView) => ({
          ...v,
          vmm: null,
          handler: null,
          jail: null,
          cgroup: null,
        }),
      ],
    ] as const) {
      const s = good();
      // Its namespace is still the agent's (a VM it forgot): only the VM itself is the fault.
      s.vms![0]!.netns.push(ns(140));
      s.vms![0]!.agentNetns.inUse.push(140);
      s.vms![0]!.vms.push(
        f({
          ...vm(VM2, 140),
          meta: { ...vm(VM2, 140).meta!, creation: "other" },
        }),
      );
      expect(rules(s), what).toEqual(["leaked-vm"]);
    }
  });

  it("does not count a VM the agent is making, or a probe VM it holds", () => {
    const s = good();
    s.vms![0]!.vms.push({
      ...vm(VM2, 132),
      meta: { ...vm(VM2, 132).meta!, creation: "mk1" },
    });
    s.vms![0]!.netns.push(ns(132));
    s.vms![0]!.veths.push(132);
    s.vms![0]!.agentNetns.inUse.push(132);
    s.agents[0]!.creating = ["mk1"];
    expect(checkInvariants(s)).toEqual([]);
    s.agents[0]!.creating = [];
    s.agents[0]!.harness!.probeVms = [{ id: VM2, address: "172.30.1.132" }];
    // Held, so not leaked; but a probe left behind after the suite is its own failure.
    expect(rules(s)).toEqual(["harness-probe-left"]);
  });

  it("finds namespaces, veths, cgroups, jails, handlers and huge pages left behind", () => {
    const a = good();
    a.vms![0]!.netns.push(ns(150));
    expect(rules(a)).toEqual(["leaked-vm-resource"]);
    const b = good();
    b.vms![0]!.veths.push(151);
    expect(rules(b)).toEqual(["leaked-vm-resource"]);
    const c = good();
    c.vms![0]!.strayCgroups.push("tpl-1759");
    expect(rules(c)).toEqual(["leaked-vm-resource"]);
    const d = good();
    d.vms![0]!.strayJails.push("tpl-1759");
    expect(rules(d)).toEqual(["leaked-vm-resource"]);
    const e = good();
    e.vms![0]!.vms[0]!.vmm = null; // the VMM died; its handler did not
    expect(rules(e)).toContain("leaked-vm-resource");
    const f = good();
    f.hugepages = { sizeKb: 2048, total: 7000, free: 5000, reserved: 0 };
    expect(rules(f)).toEqual(["leaked-hugepages"]);
    const g = good();
    g.agents[0]!.sessions = [];
    g.api = [];
    g.egress[0]!.policies = [];
    g.gateways[0]!.routes = [];
    g.vms![0]!.vms = [];
    g.vms![0]!.netns = [ns(131)];
    g.vms![0]!.veths = [131];
    g.vms![0]!.agentNetns.inUse = [];
    g.hugepages = { sizeKb: 2048, total: 7000, free: 7000, reserved: 2 };
    // No VM runs: any page held at all is a leak.
    expect(rules(g)).toEqual(["leaked-hugepages"]);
  });

  it("fails each weakening of a VM's hardening, and only that", () => {
    const cases: [string, (s: Snapshot) => void][] = [
      ["root VMM", (s) => (s.vms![0]!.vms[0]!.vmm!.uid = [0, 0])],
      [
        "a capability",
        (s) => (s.vms![0]!.vms[0]!.vmm!.capEff = "0000000000003000"),
      ],
      ["no seccomp", (s) => (s.vms![0]!.vms[0]!.vmm!.seccomp = 0)],
      ["new privileges", (s) => (s.vms![0]!.vms[0]!.vmm!.noNewPrivs = false)],
      [
        "host PID namespace",
        (s) => (s.vms![0]!.vms[0]!.vmm!.pidNs = "pid:[4026531836]"),
      ],
      [
        "host mount namespace",
        (s) => (s.vms![0]!.vms[0]!.vmm!.mntNs = "mnt:[4026531841]"),
      ],
      [
        "outside its jail",
        (s) => (s.vms![0]!.vms[0]!.vmm!.root = { dev: 66306, ino: 2 }),
      ],
      [
        "another namespace",
        (s) => (s.vms![0]!.vms[0]!.vmm!.netNs = "net:[4026531840]"),
      ],
      [
        "another cgroup",
        (s) => (s.vms![0]!.vms[0]!.vmm!.cgroup = "/system.slice"),
      ],
      ["more CPU", (s) => (s.vms![0]!.vms[0]!.cgroup!.cpuMax = "max 100000")],
      ["more memory", (s) => (s.vms![0]!.vms[0]!.cgroup!.memoryMax = "max")],
      ["swap", (s) => (s.vms![0]!.vms[0]!.cgroup!.swapMax = "max")],
      ["no process limit", (s) => (s.vms![0]!.vms[0]!.cgroup!.pidsMax = "max")],
      ["no cgroup", (s) => (s.vms![0]!.vms[0]!.cgroup = null)],
      ["handler lost", (s) => (s.vms![0]!.vms[0]!.handler = null)],
      ["root handler", (s) => (s.vms![0]!.vms[0]!.handler!.uid = [0, 0])],
      [
        "handler outside the cgroup",
        (s) => (s.vms![0]!.vms[0]!.handler!.cgroup = "/"),
      ],
    ];
    for (const [what, f] of cases) {
      const s = good();
      f(s);
      expect(rules(s), what).toEqual(["vm-not-hardened"]);
    }
  });

  it("checks every namespace's rules and IPv6, ready ones too", () => {
    const a = good();
    a.vms![0]!.netns[1]!.rules = GOOD_RULES.replace(
      ":FORWARD DROP",
      ":FORWARD ACCEPT",
    );
    expect(rules(a)).toEqual(["vm-netns-rules"]);
    const b = good();
    b.vms![0]!.netns[0]!.ipv6Disabled = false;
    expect(rules(b)).toEqual(["vm-netns-rules"]);
    const c = good();
    c.vms![0]!.netns[0]!.rules = null;
    expect(rules(c)).toEqual(["vm-netns-rules"]);
  });

  it("finds a ready session whose VM is not running, or is gone", () => {
    const a = good();
    a.vms![0]!.vms[0]!.vmm = null;
    a.vms![0]!.vms[0]!.handler = null;
    a.hugepages = null;
    expect(rules(a)).toEqual(["vm-not-running"]);
    const b = good();
    b.vms![0]!.vms = [];
    expect(rules(b)).toContain("binding-without-container");
  });

  it("names what is wrong", () => {
    const s = good();
    s.vms![0]!.vms[0]!.vmm!.uid = [0, 0];
    expect(details(s)[0]).toMatch(/runs as uid 0\/0/);
  });
});
